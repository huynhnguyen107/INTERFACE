module xxv_ctrl (

    // =========================================================
    // TX CONTROL
    // Same order as xxv_ethernet_0 ports in Block Design
    // =========================================================

    output wire        ctl_tx_custom_preamble_enable_0,
    output wire        ctl_tx_data_pattern_select_0,
    output wire        ctl_tx_enable_0,
    output wire        ctl_tx_fcs_ins_enable_0,
    output wire        ctl_tx_ignore_fcs_0,
    output wire [3:0]  ctl_tx_ipg_value_0,
    output wire        ctl_tx_send_idle_0,
    output wire        ctl_tx_send_lfi_0,
    output wire        ctl_tx_send_rfi_0,
    output wire        ctl_tx_test_pattern_0,
    output wire        ctl_tx_test_pattern_enable_0,
    output wire [57:0] ctl_tx_test_pattern_seed_a_0,
    output wire [57:0] ctl_tx_test_pattern_seed_b_0,
    output wire        ctl_tx_test_pattern_select_0,

    // =========================================================
    // RX CONTROL
    // Same order as xxv_ethernet_0 ports in Block Design
    // =========================================================

    output wire        ctl_rx_check_preamble_0,
    output wire        ctl_rx_check_sfd_0,
    output wire        ctl_rx_custom_preamble_enable_0,
    output wire        ctl_rx_data_pattern_select_0,
    output wire        ctl_rx_delete_fcs_0,
    output wire        ctl_rx_enable_0,
    output wire        ctl_rx_force_resync_0,
    output wire        ctl_rx_ignore_fcs_0,
    output wire [14:0] ctl_rx_max_packet_len_0,
    output wire [7:0]  ctl_rx_min_packet_len_0,
    output wire        ctl_rx_process_lfi_0,
    output wire        ctl_rx_test_pattern_0,
    output wire        ctl_rx_test_pattern_enable_0
);


    // =========================================================
    // TX CONFIGURATION
    // =========================================================

    // Standard Ethernet preamble generated by MAC
    assign ctl_tx_custom_preamble_enable_0 = 1'b0;

    // Normal Ethernet data, not test-pattern data
    assign ctl_tx_data_pattern_select_0 = 1'b0;

    // Enable TX MAC
    assign ctl_tx_enable_0 = 1'b1;

    // MAC automatically generates and inserts Ethernet FCS
    assign ctl_tx_fcs_ins_enable_0 = 1'b1;

    assign ctl_tx_ignore_fcs_0 = 1'b0;

    // Standard Ethernet inter-packet gap
    assign ctl_tx_ipg_value_0 = 4'd12;

    // Do not force Idle / Local Fault / Remote Fault
    assign ctl_tx_send_idle_0 = 1'b0;
    assign ctl_tx_send_lfi_0  = 1'b0;
    assign ctl_tx_send_rfi_0  = 1'b0;

    // Disable built-in MAC test-pattern generator
    assign ctl_tx_test_pattern_0        = 1'b0;
    assign ctl_tx_test_pattern_enable_0 = 1'b0;

    assign ctl_tx_test_pattern_seed_a_0 = 58'd0;
    assign ctl_tx_test_pattern_seed_b_0 = 58'd0;

    assign ctl_tx_test_pattern_select_0 = 1'b0;


    // =========================================================
    // RX CONFIGURATION
    // =========================================================

    // Check standard Ethernet preamble and SFD
    assign ctl_rx_check_preamble_0 = 1'b1;
    assign ctl_rx_check_sfd_0      = 1'b1;

    // Standard Ethernet preamble
    assign ctl_rx_custom_preamble_enable_0 = 1'b0;

    // Normal Ethernet data, not test pattern
    assign ctl_rx_data_pattern_select_0 = 1'b0;

    // Remove received FCS before outputting frame on AXI Stream
    assign ctl_rx_delete_fcs_0 = 1'b1;

    // Enable RX MAC
    assign ctl_rx_enable_0 = 1'b1;

    // No manual PCS resynchronization
    assign ctl_rx_force_resync_0 = 1'b0;

    // Do not ignore bad FCS
    assign ctl_rx_ignore_fcs_0 = 1'b0;

    // Jumbo-capable maximum packet size
    assign ctl_rx_max_packet_len_0 = 15'd9216;

    // Standard minimum Ethernet frame size
    assign ctl_rx_min_packet_len_0 = 8'd64;

    // Do not specially process Local Fault indication
    assign ctl_rx_process_lfi_0 = 1'b0;

    // Disable RX test-pattern mode
    assign ctl_rx_test_pattern_0        = 1'b0;
    assign ctl_rx_test_pattern_enable_0 = 1'b0;


endmodule